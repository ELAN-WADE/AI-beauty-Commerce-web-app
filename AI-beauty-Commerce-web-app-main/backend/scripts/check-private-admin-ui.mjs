import assert from 'node:assert/strict';
import dotenv from 'dotenv';
import { chromium } from '@playwright/test';
for (const file of ['.env.development.local', '.env.local', '.env.development', '.env']) dotenv.config({ path: file });
const entry = process.env.ADMIN_ENTRY_PATH;
if (!entry || !process.env.LOCAL_ADMIN_PASSWORD) throw new Error('Private admin configuration is missing.');
const origin = 'http://localhost:3000';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const context = await browser.newContext(); const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin + entry, { waitUntil: 'domcontentloaded', timeout: 120000 });
  await page.getByRole('heading', { name: 'Administrator sign in', exact: true }).waitFor({ timeout: 120000 });
  assert.equal(new URL(page.url()).pathname, entry);
  assert.equal(await page.getByLabel('Password', { exact: true }).inputValue(), '');
  await page.getByLabel('Administrator email', { exact: true }).fill(process.env.ADMIN_GOOGLE_EMAIL);
  await page.getByLabel('Password', { exact: true }).fill(process.env.LOCAL_ADMIN_PASSWORD);
  const response = page.waitForResponse(r => r.url().endsWith('/api/auth/admin/login') && r.request().method() === 'POST', { timeout: 120000 });
  await page.getByRole('button', { name: 'Sign in as administrator', exact: true }).click();
  assert.equal((await response).status(), 200);
  await page.getByLabel('Authenticator or recovery code', { exact: true }).waitFor({ timeout: 120000 });
  const meResponse = await page.request.get(origin + '/api/auth/me');
  assert.equal(meResponse.status(), 200);
  const me = await meResponse.json(); assert.equal(me.email, process.env.ADMIN_GOOGLE_EMAIL); assert.equal(me.adminEntryPath, entry); assert.equal(me.mfaVerified, false);
  const protectedResponse = await page.request.get(origin + '/api/admin/products');
  assert.equal(protectedResponse.status(), 403); assert.equal((await protectedResponse.json()).error.code, 'mfa_required');
  await page.request.post(origin + '/api/auth/logout', { headers: { origin } });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Administrator sign in', exact: true }).waitFor({ timeout: 120000 });
  await page.route('https://accounts.google.com/**', route => route.abort());
  const provider = page.waitForRequest(req => new URL(req.url()).hostname === 'accounts.google.com', { timeout: 120000 });
  await page.getByRole('button', { name: 'Continue with administrator Google account', exact: true }).click();
  const google = new URL((await provider).url()); assert.equal(google.searchParams.get('login_hint'), process.env.ADMIN_GOOGLE_EMAIL);
  const callback = new URL(google.searchParams.get('redirect_uri')); callback.searchParams.set('state', google.searchParams.get('state')); callback.searchParams.set('error', 'access_denied');
  await page.goto(callback.toString(), { waitUntil: 'domcontentloaded', timeout: 120000 });
  assert.equal(new URL(page.url()).pathname, entry);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ privateAdminPage: 'rendered', configuredPasswordLogin: 'passed', mfaStillRequired: true, adminGoogleStartAndCancel: 'passed', runtimeErrors: 0 }));
} finally { await browser.close(); }
